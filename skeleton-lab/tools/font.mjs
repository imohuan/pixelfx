export function drawText(buf, W, str, x, y, [r, g, b], scale = 2) {
  let cx = x;
  for (const ch of str) {
    const glyph = F[ch] || F["?"] || F[" "];
    if (glyph) {
      for (let row = 0; row < 7; row++) {
        for (let col = 0; col < 5; col++) {
          if (glyph[row] & (1 << (4 - col))) {
            for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
              const px = cx + col * scale + sx, py = y + row * scale + sy;
              if (px < 0 || py < 0 || px >= W || py >= buf.length / (W * 4)) continue;
              const j = (py * W + px) * 4;
              buf[j] = r; buf[j+1] = g; buf[j+2] = b; buf[j+3] = 255;
            }
          }
        }
      }
    }
    cx += 6 * scale;
  }
  return cx;
}
