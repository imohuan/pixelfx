#!/usr/bin/env node
// The one build step: demo/src/entry.js -> demo/pixelfx.js (one file a browser can run).
//
//   node demo/build.mjs              -> demo/pixelfx.js
//   node demo/build.mjs --esm        -> demo/pixelfx.mjs
//   node demo/build.mjs --minify=0   readable, for debugging
//
// No effect files go in. The page brings its own code; this file only supplies the kit and the player.

import { statSync, readdirSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
};
const esm = args.includes("--esm");
const file = join(HERE, esm ? "pixelfx.mjs" : "pixelfx.js");

// The kit is every module an effect may import from: core, plus each category's _lib.js. Generating the
// list from disk means a new category needs no edit here, and nothing silently goes missing.
const kits = readdirSync(join(ROOT, "src", "fx"), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .filter((c) => {
    try {
      return statSync(join(ROOT, "src", "fx", c, "_lib.js")).isFile();
    } catch {
      return false;
    }
  })
  .sort();

const ident = (s) => s.replace(/[^a-z0-9]+/gi, "_");
const kitSource = [
  "// Auto-generated by demo/build.mjs — do not edit by hand.",
  "// Every module an effect may import from: src/core plus each src/fx/<category>/_lib.js.",
  "",
  'import * as core from "../../src/core/index.js";',
  ...kits.map((c) => `import * as ${ident(c)} from "../../src/fx/${c}/_lib.js";`),
  "",
  `export const modules = { core, ${kits.map((c) => `${ident(c)}`).join(", ")} };`,
  "",
  `export const kit = { ...core, ${kits.map((c) => `...${ident(c)}`).join(", ")} };`,
  "",
].join("\n");
writeFileSync(join(HERE, "src", "kit.js"), kitSource);

await build({
  entryPoints: [join(HERE, "src", "entry.js")],
  bundle: true,
  format: esm ? "esm" : "iife",
  minify: opt("minify", "1") !== "0",
  sourcemap: opt("minify", "1") === "0",
  target: ["es2020"],
  legalComments: "none",
  logLevel: "warning",
  outfile: file,
});

// The UI font has to sit next to the bundle: a page anywhere can load it by a URL relative to this script.
mkdirSync(join(HERE, "fonts"), { recursive: true });
copyFileSync(join(ROOT, "gallery", "fonts", "PatchPixel-Regular.woff2"), join(HERE, "fonts", "PatchPixel-Regular.woff2"));

console.log(`${(statSync(file).size / 1024).toFixed(1).padStart(6)} KB  demo/${esm ? "pixelfx.mjs" : "pixelfx.js"}`);
console.log(`      fonts/PatchPixel-Regular.woff2`);
