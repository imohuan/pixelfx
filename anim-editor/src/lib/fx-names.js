/** 特效 id → 中文名；无映射时回退英文名 */
export function fxNameCn(id) {
  if (!id) return "";
  if (OVERRIDES[id]) return OVERRIDES[id];
  const words = String(id).split("/").pop().split("-");
  const parts = words.map((w) => WORDS[w.toLowerCase()] ?? w);
  return parts.join("");
}

/** 分类 id → 中文名 */
export function categoryNameCn(id) {
  return CATEGORY_CN[id] ?? id;
}
